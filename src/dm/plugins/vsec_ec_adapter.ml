(* Command execution adapter using functional process_internal *)
let process_command (scope: EcLib.EcScope.scope) (command: string) : EcLib.EcScope.scope =
  try
    log (fun () -> Printf.sprintf "[Adapter] Processing command: %s" command);
    
    (* Parse the command *)
    let reader = EcLib.EcIo.from_string command in
    let prog = EcLib.EcIo.parse reader in
    EcLib.EcIo.finalize reader;
    
    (* Extract global actions from prog *)
    let actions = match EcLib.EcLocation.unloc prog with
      | EcLib.EcParsetree.P_Prog (globals, _) -> 
          List.map (fun g -> g.EcLib.EcParsetree.gl_action) globals
      | EcLib.EcParsetree.P_Exit -> []
      | EcLib.EcParsetree.P_Undo _ -> []
    in
    
    (* Execute each action using functional process_internal *)
    (* This avoids global state and allows per-document scopes *)
    let final_scope = List.fold_left (fun current_scope action ->
      try
        (* Use process_internal for functional scope updates *)
        let new_scope = EcLib.EcCommands.process_internal 
          EcLib.EcCommands.loader 
          current_scope 
          action in
        log (fun () -> "[Adapter] Command executed successfully");
        new_scope
      with exn ->
        log (fun () -> Printf.sprintf "[Adapter] Command execution failed: %s" (Printexc.to_string exn));
        (* On error, return current scope (don't propagate partial state) *)
        raise exn
    ) scope actions in
    
    log (fun () -> "[Adapter] Scope updated functionally");
    final_scope
    
  with exn ->
    log (fun () -> Printf.sprintf "[Adapter] process_command failed: %s" (Printexc.to_string exn));
    (* Return original scope on error - maintains consistency *)
    scope

