let classify_ast_kind (kind: string) : string option =
  Hashtbl.find_opt tag_mapping kind

(* Convert AST JSON to proper pp_atoms for UI rendering *)
let rec json_to_pp_atoms (json: Yojson.Safe.t) : PS.pp =
  match json with
  | `Assoc fields ->
      (* Check for 'node' field first (wrapping structure) *)
      (match List.assoc_opt "node" fields with
      | Some node_json -> json_to_pp_atoms node_json
      | None ->
          (* Direct AST node - extract kind and content *)
          (match List.assoc_opt "kind" fields with
          | Some (`String kind) ->
              let cls = classify_ast_kind kind in
              
              (* Extract text representation based on kind *)
              (match kind with
              (* Quantifiers *)
              | "quant" ->
                  (match List.assoc_opt "quantifier" fields, List.assoc_opt "bindings" fields, List.assoc_opt "body" fields with
                  | Some (`String q), Some bindings_json, Some body_json ->
                      let q_atom = { PS.text = q; cls = Some "keyword" } in
                      let space = { PS.text = " "; cls = None } in
                      let bindings = json_to_pp_atoms bindings_json in
                      let dot = { PS.text = ", "; cls = None } in
                      let body = json_to_pp_atoms body_json in
                      q_atom :: space :: bindings @ [dot] @ body
                  | _ -> [ { PS.text = kind; cls } ])
              
              (* Conditionals *)
              | "if" ->
                  (match List.assoc_opt "condition" fields, List.assoc_opt "then" fields, List.assoc_opt "else" fields with
                  | Some cond_json, Some then_json, Some else_json ->
                      let if_atom = { PS.text = "if "; cls = Some "keyword" } in
                      let then_atom = { PS.text = " then "; cls = Some "keyword" } in
                      let else_atom = { PS.text = " else "; cls = Some "keyword" } in
                      let cond = json_to_pp_atoms cond_json in
                      let then_part = json_to_pp_atoms then_json in
                      let else_part = json_to_pp_atoms else_json in
                      [if_atom] @ cond @ [then_atom] @ then_part @ [else_atom] @ else_part
                  | _ -> [ { PS.text = "if"; cls = Some "keyword" } ])
              
              (* Integers *)
              | "int" ->
                  (match List.assoc_opt "value" fields with
                  | Some (`String v) -> [ { PS.text = v; cls = Some "number" } ]
                  | Some _ | None -> [ { PS.text = "0"; cls = Some "number" } ])
              
              (* Local variables *)
              | "local" | "var" ->
                  (match List.assoc_opt "id" fields with
                  | Some id_json ->
                      (match json_to_pp_atoms id_json with
                      | [] -> [ { PS.text = kind; cls = Some "variable" } ]
                      | atoms -> List.map (fun a -> { a with PS.cls = Some "variable" }) atoms)
                  | None ->
                      (match List.assoc_opt "name" fields with
                      | Some (`String name) -> [ { PS.text = name; cls = Some "variable" } ]
                      | Some _ | None -> [ { PS.text = kind; cls = Some "variable" } ]))
              
              (* Operators *)
              | "op" ->
                  (match List.assoc_opt "path" fields with
                  | Some (`String p) -> [ { PS.text = p; cls = Some "function" } ]
                  | Some _ | None -> [ { PS.text = "op"; cls = Some "function" } ])
              
              (* Function application *)
              | "app" ->
                  (match List.assoc_opt "func" fields, List.assoc_opt "args" fields with
                  | Some func_json, Some (`List args) ->
                      let func = json_to_pp_atoms func_json in
                      let args_atoms = List.concat (List.map json_to_pp_atoms args) in
                      let lparen = { PS.text = "("; cls = None } in
                      let rparen = { PS.text = ")"; cls = None } in
                      func @ [lparen] @ args_atoms @ [rparen]
                  | _ -> [ { PS.text = "app"; cls = Some "function" } ])
              
              (* Tuples *)
              | "tuple" ->
                  (match List.assoc_opt "elements" fields with
                  | Some (`List elems) ->
                      let elem_atoms = List.map json_to_pp_atoms elems in
                      let comma = { PS.text = ", "; cls = None } in
                      let lparen = { PS.text = "("; cls = None } in
                      let rparen = { PS.text = ")"; cls = None } in
                      let rec intersperse sep = function
                        | [] -> []
                        | [x] -> x
                        | x :: xs -> x @ [sep] @ intersperse sep xs
                      in
                      [lparen] @ intersperse comma elem_atoms @ [rparen]
                  | _ -> [ { PS.text = "()"; cls = None } ])
              
              (* Type constructors *)
              | "constr" ->
                  (match List.assoc_opt "path" fields with
                  | Some (`String p) -> [ { PS.text = p; cls = Some "type" } ]
                  | Some _ | None -> [ { PS.text = kind; cls = Some "type" } ])
              
              (* Function types *)
              | "fun" ->
                  (match List.assoc_opt "domain" fields, List.assoc_opt "codomain" fields with
                  | Some dom_json, Some cod_json ->
                      let dom = json_to_pp_atoms dom_json in
                      let arrow = { PS.text = " -> "; cls = Some "keyword" } in
                      let cod = json_to_pp_atoms cod_json in
                      dom @ [arrow] @ cod
                  | _ -> [ { PS.text = "->"; cls = Some "keyword" } ])
              
              (* Identifiers (extract name) *)
              | _ ->
                  (match List.assoc_opt "name" fields with
                  | Some (`String name) -> [ { PS.text = name; cls } ]
                  | Some _ | None ->
                      (match List.assoc_opt "id" fields with
                      | Some id_json -> json_to_pp_atoms id_json
                      | None -> [ { PS.text = kind; cls } ])))
          
          | _ ->
              (* No kind field - check for direct string fields *)
              (match List.assoc_opt "name" fields with
              | Some (`String name) -> [ { PS.text = name; cls = None } ]
              | Some _ | None -> [ { PS.text = Yojson.Safe.to_string json; cls = None } ])))
  
  | `String s -> [ { PS.text = s; cls = None } ]
  | `Int i -> [ { PS.text = string_of_int i; cls = Some "number" } ]
  | `List items ->
      (* Flatten list of atoms *)
      List.concat (List.map json_to_pp_atoms items)
  | `Null -> []
  | _ -> [ { PS.text = Yojson.Safe.to_string json; cls = None } ]

(* Convert AST JSON to legacy string (for backward compat) *)
let pp_to_legacy_string (json: Yojson.Safe.t) : string =
  (* Convert to pp_atoms and concatenate text *)
  let atoms = json_to_pp_atoms json in
  String.concat "" (List.map (fun (a: PS.pp_atom) -> a.text) atoms)

(* Extract goals using AST serialization - NO MORE TEXT CONVERSION! *)
let extract_goals_with_ast goals ~id_offset =
  let to_goal idx (pg:EcLib.EcCoreGoal.pregoal) : PS.goal =
    log (fun () -> Printf.sprintf "[Adapter] Extracting goal %d using AST serialization" idx);
    
    (* Extract hypotheses as structured AST *)
    let hyps = EcLib.EcEnv.LDecl.tohyps pg.EcLib.EcCoreGoal.g_hyps in
    let hyps_json = List.map Ast.yojson_of_hypothesis hyps.h_local in
    
    (* Extract conclusion as structured AST *)
    let concl_json = Ast.yojson_of_form pg.EcLib.EcCoreGoal.g_concl in
    
    (* Legacy string representation (temporary during migration) *)
    let hyps_str = List.map pp_to_legacy_string hyps_json in
    let concl_str = pp_to_legacy_string concl_json in
    
    (* Convert to pp format *)
    let hyps_pp = List.map json_to_pp_atoms hyps_json in
    let concl_pp = json_to_pp_atoms concl_json in
    
    log (fun () -> Printf.sprintf "[Adapter] Goal %d: %d hypotheses extracted via AST" idx (List.length hyps.h_local));
    
    { PS.id = id_offset + idx
    ; hypotheses = hyps_str
    ; goal = concl_str
    ; hypotheses_pp = hyps_pp
    ; goal_pp = concl_pp
    }
  in
  List.mapi to_goal goals

let goals_of_scope (scope:EcLib.EcScope.scope) : PS.goal list =
  match EcLib.EcScope.xgoal scope with
  | None -> []
  | Some { EcLib.EcScope.puc_active = None; _ } -> []
  | Some { EcLib.EcScope.puc_active = Some (puc, _); _ } ->
    begin match puc.EcLib.EcScope.puc_jdg with
    | EcLib.EcScope.PSNoCheck -> []
    | EcLib.EcScope.PSCheck proof ->
      let opened = EcLib.EcCoreGoal.all_opened proof in
      (* NO MORE pp_form_to_string! Use AST serialization directly *)
      extract_goals_with_ast opened ~id_offset:0
    end

